"""Ask the Genie space benchmark questions and save the answers (SQL + result rows) as text evidence.

Usage: python scripts/ask_genie.py <profile> <space_id> [out.md] [question ...]
"""
import json, subprocess, sys, time
from datetime import datetime, timezone

PROFILE, SPACE = sys.argv[1], sys.argv[2]
OUT = sys.argv[3] if len(sys.argv) > 3 else None
QUESTIONS = sys.argv[4:] or [
    "What share of products was enriched automatically per market?",
    "What is the high-protein share of snack bars in Spain vs the US?",
    "How many products are waiting for analyst review, by market and evidence tier?",
    "Which 5 brands have the most protein per bar on average (at least 3 products)?",
    "How did automation rate change from week to week?",
    "How much did enrichment cost per 1,000 products and how many analyst hours did it save, per week?",
]


def api(method, path, body=None):
    cmd = ["databricks", "api", method, path, "-p", PROFILE] + (["--json", json.dumps(body)] if body else [])
    out = subprocess.run(cmd, capture_output=True, text=True)
    return json.loads(out.stdout)


lines = [f"# Genie evidence: {datetime.now(timezone.utc):%Y-%m-%d %H:%M UTC}", "",
         f"Space `{SPACE}` (Northbeam · Snack Bar Product Intelligence). Answers below are copied from the Genie API.", ""]
for q in QUESTIONS:
    r = api("post", f"/api/2.0/genie/spaces/{SPACE}/start-conversation", {"content": q})
    conv, msg = r["conversation_id"], r["message_id"]
    for _ in range(60):
        m = api("get", f"/api/2.0/genie/spaces/{SPACE}/conversations/{conv}/messages/{msg}")
        if m.get("status") in ("COMPLETED", "FAILED", "CANCELLED"):
            break
        time.sleep(3)
    lines += [f"## Q: {q}", f"status: {m.get('status')}", ""]
    for a in m.get("attachments", []) or []:
        if a.get("text"):
            lines += ["**Answer:** " + a["text"]["content"], ""]
        if a.get("query"):
            lines += ["**SQL generated by Genie:**", "```sql", a["query"]["query"].strip(), "```"]
            if a["query"].get("description"):
                lines += ["", "_" + a["query"]["description"] + "_"]
            res = api("get", f"/api/2.0/genie/spaces/{SPACE}/conversations/{conv}/messages/{msg}/attachments/{a['attachment_id']}/query-result")
            sr = res.get("statement_response", {})
            cols = [c["name"] for c in sr.get("manifest", {}).get("schema", {}).get("columns", [])]
            rows = sr.get("result", {}).get("data_array", []) or []
            if cols:
                lines += ["", "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
                lines += ["| " + " | ".join("" if v is None else str(v) for v in row) + " |" for row in rows[:15]]
            lines.append("")
    print(f"{m.get('status')}: {q}")
text = "\n".join(lines)
if OUT:
    open(OUT, "w").write(text)
else:
    print(text)
